-- Additive reporting and atomic leave review. No existing records are removed.
BEGIN;
CREATE TABLE IF NOT EXISTS hr_report_settings (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id INTEGER NOT NULL UNIQUE REFERENCES companies(id),
 enabled BOOLEAN NOT NULL DEFAULT false,
 recipients JSONB NOT NULL DEFAULT '[]',
 updated_by INTEGER REFERENCES users(id), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(jsonb_typeof(recipients)='array' AND jsonb_array_length(recipients)<=20)
);
CREATE TABLE IF NOT EXISTS hr_report_runs (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id INTEGER NOT NULL REFERENCES companies(id), report_date DATE NOT NULL,
 snapshot JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(company_id,report_date)
);
CREATE TABLE IF NOT EXISTS hr_report_deliveries (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id INTEGER NOT NULL REFERENCES companies(id), run_id INTEGER NOT NULL REFERENCES hr_report_runs(id),
 recipient TEXT NOT NULL, state TEXT NOT NULL CHECK(state IN ('sending','accepted','failed','uncertain')),
 attempts INTEGER NOT NULL DEFAULT 1, message_id TEXT, error TEXT,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(run_id,recipient)
);
INSERT INTO hr_report_settings(company_id,enabled,recipients)
 SELECT id,true,'["hr@experiential-edge.com"]'::jsonb FROM companies WHERE id=1 ON CONFLICT(company_id) DO NOTHING;
CREATE OR REPLACE FUNCTION hr_report_prepare(p_company_id INTEGER,p_day DATE,p_snapshot JSONB)
RETURNS JSONB LANGUAGE plpgsql SET search_path=public AS $$
DECLARE r hr_report_runs;
BEGIN
 INSERT INTO hr_report_runs(company_id,report_date,snapshot) VALUES(p_company_id,p_day,p_snapshot)
 ON CONFLICT(company_id,report_date) DO NOTHING;
 SELECT * INTO r FROM hr_report_runs WHERE company_id=p_company_id AND report_date=p_day;
 RETURN to_jsonb(r);
END; $$;
CREATE OR REPLACE FUNCTION hr_report_claim(p_company_id INTEGER,p_run_id INTEGER,p_recipient TEXT)
RETURNS JSONB LANGUAGE plpgsql SET search_path=public AS $$
DECLARE r hr_report_deliveries;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM hr_report_runs WHERE id=p_run_id AND company_id=p_company_id) THEN RAISE EXCEPTION 'Report not found'; END IF;
 INSERT INTO hr_report_deliveries(company_id,run_id,recipient,state) VALUES(p_company_id,p_run_id,p_recipient,'sending')
 ON CONFLICT(run_id,recipient) DO UPDATE SET state='sending',attempts=hr_report_deliveries.attempts+1,error=NULL,updated_at=now()
 WHERE hr_report_deliveries.state='failed' AND hr_report_deliveries.updated_at<now()-interval '5 minutes'
 RETURNING * INTO r;
 IF r.id IS NULL THEN RETURN NULL; END IF;
 RETURN to_jsonb(r);
END; $$;
CREATE OR REPLACE FUNCTION hr_reporting_readiness() RETURNS BOOLEAN LANGUAGE sql SET search_path=public AS $$
 SELECT to_regclass('public.hr_report_settings') IS NOT NULL AND to_regclass('public.hr_report_runs') IS NOT NULL AND to_regprocedure('public.hr_review_leave(integer,integer,integer,boolean,text)') IS NOT NULL;
$$;
REVOKE ALL ON FUNCTION hr_reporting_readiness() FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION hr_reporting_readiness() TO service_role;
CREATE OR REPLACE FUNCTION hr_review_leave(p_company_id INTEGER,p_actor_id INTEGER,p_request_id INTEGER,p_approve BOOLEAN,p_reason TEXT)
RETURNS JSONB LANGUAGE plpgsql SET search_path=public AS $$
DECLARE r leave_requests; k TEXT; result leave_requests; changed INTEGER;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM users WHERE id=p_actor_id AND company_id=p_company_id AND status='active' AND role_code IN ('HR','HR_MANAGER','ADMIN','SUPER_ADMIN','CEO','CTO','IT_ADMIN','MANAGER')) THEN RAISE EXCEPTION 'Unauthorized leave reviewer'; END IF;
 SELECT * INTO r FROM leave_requests WHERE id=p_request_id AND company_id=p_company_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Leave request not found'; END IF;
 IF r.status<>'pending' THEN RAISE EXCEPTION 'Leave request has already been reviewed'; END IF;
 IF p_approve THEN
   k:=lower(r.leave_type);
   IF k IN ('annual','sick','casual') THEN
     EXECUTE format('UPDATE leave_balances SET %I=%I-$1 WHERE employee_id=$2 AND year=$3 AND %I >= $1',k,k,k) USING r.days,r.employee_id,extract(year FROM r.start_date)::integer;
     GET DIAGNOSTICS changed=ROW_COUNT;
     IF changed<>1 THEN RAISE EXCEPTION 'Leave balance is missing or insufficient. Update the balance before approval'; END IF;
   END IF;
 END IF;
 UPDATE leave_requests SET status=CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END, reviewed_by=p_actor_id,reviewed_at=now(),review_notes=p_reason WHERE id=r.id RETURNING * INTO result;
 INSERT INTO notifications(company_id,employee_id,type,title,body) VALUES(p_company_id,r.employee_id,'Leave',CASE WHEN p_approve THEN 'Leave approved' ELSE 'Leave request update' END, r.leave_type||' leave ('||r.start_date||' to '||r.end_date||'): '||result.status||'. '||coalesce(p_reason,''));
 RETURN to_jsonb(result);
END; $$;
ALTER TABLE hr_report_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE hr_report_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE hr_report_deliveries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON hr_report_settings,hr_report_runs,hr_report_deliveries FROM PUBLIC,anon,authenticated;
GRANT ALL ON hr_report_settings,hr_report_runs,hr_report_deliveries TO service_role;
GRANT USAGE,SELECT ON SEQUENCE hr_report_settings_id_seq,hr_report_runs_id_seq,hr_report_deliveries_id_seq TO service_role;
REVOKE ALL ON FUNCTION hr_report_prepare(INTEGER,DATE,JSONB),hr_report_claim(INTEGER,INTEGER,TEXT),hr_review_leave(INTEGER,INTEGER,INTEGER,BOOLEAN,TEXT) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION hr_report_prepare(INTEGER,DATE,JSONB),hr_report_claim(INTEGER,INTEGER,TEXT),hr_review_leave(INTEGER,INTEGER,INTEGER,BOOLEAN,TEXT) TO service_role;
NOTIFY pgrst,'reload schema';
COMMIT;
