function sql(input, failureExpected = false) {
  const result = spawnSync('docker', ['exec', '-i', container, 'psql', '-U', 'postgres', '-d', database, '-v', 'ON_ERROR_STOP=1', '-A', '-t'], { input, encoding: 'utf8' });
  if (!failureExpected && result.status !== 0) throw new Error(result.stderr || 'PostgreSQL test transport failed.');
  return result;
}
function pgType(column) {
  if (column.format === 'jsonb') return 'JSONB';
  if (column.format === 'integer[]') return 'INTEGER[]';
  if (column.format === 'text[]') return 'TEXT[]';
  if (column.type === 'integer') return 'INTEGER';
  if (column.type === 'number') return 'NUMERIC';
  if (column.type === 'boolean') return 'BOOLEAN';
  if (column.format === 'timestamp with time zone') return 'TIMESTAMPTZ';
  if (column.format === 'date') return 'DATE';
  if (column.format === 'uuid') return 'UUID';
  return 'TEXT';
}
